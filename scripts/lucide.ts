const dir = process.argv[2];
if (!dir) throw new Error("usage: node scripts/lucide.ts <lucide-static package dir>");
const version = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")).version as string;

const inner = (file: string) => {
  const svg = readFileSync(join(dir, "icons", `${file}.svg`), "utf8");
  const body = /<svg[^>]*>([\s\S]*?)<\/svg>/.exec(svg)?.[1];
  if (!body) throw new Error(`no <svg> in ${file}`);
  return body
    .replace(/\s+class="[^"]*"/g, "")
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean)
    .join("");
};

const lines = Object.entries(NAME).map(([ours, file]) => `  ${ours}: \`${inner(file)}\`,`);
const out = `// Lucide icons (ISC, lucide-static ${version}) — the set T3 Code's UI uses. Generated by scripts/lucide.ts; do not edit by hand.
export const LUCIDE = {
${lines.join("\n")}
} as const;
export type LucideName = keyof typeof LUCIDE;
`;
writeFileSync(new URL("../src/core/icons.ts", import.meta.url), out);
